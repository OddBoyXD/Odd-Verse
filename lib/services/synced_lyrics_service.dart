  static Future<Map<String, dynamic>?> _fetchFromYouTubeCaptions(
      String videoId) async {
    final yt = YoutubeExplode();
    try {
      final manifest = await yt.videos.closedCaptions.getManifest(videoId);
      if (manifest.tracks.isEmpty) return null;

      ClosedCaptionTrackInfo? selectedTrack;
      // Prioritize non-auto-generated official tracks first, then en/hi, then any
      for (final track in manifest.tracks) {
        if (!track.isAutoGenerated) {
          selectedTrack = track;
          break;
        }
      }
      if (selectedTrack == null) {
        for (final track in manifest.tracks) {
          final lang = track.language.code.toLowerCase();
          if (lang == 'en' || lang == 'hi' || lang.startsWith('en-') || lang.startsWith('hi-')) {
            selectedTrack = track;
            break;
          }
        }
      }
      selectedTrack ??= manifest.tracks.first;

      final track = await yt.videos.closedCaptions.get(selectedTrack);
      if (track.captions.isEmpty) return null;

      final buffer = StringBuffer();
      final plainBuffer = StringBuffer();

      Duration? firstCaptionOffset;
      for (final caption in track.captions) {
        final text = caption.text.trim();
        if (text.isEmpty) continue;

        final offset = caption.offset;
        firstCaptionOffset ??= offset;

        final minutes =
            offset.inMinutes.remainder(60).toString().padLeft(2, '0');
        final seconds =
            offset.inSeconds.remainder(60).toString().padLeft(2, '0');
        final ms = (offset.inMilliseconds.remainder(1000) ~/ 10)
            .toString()
            .padLeft(2, '0');

        buffer.writeln('[$minutes:$seconds.$ms]$text');
        plainBuffer.writeln(text);
      }

      final syncedLrc = buffer.toString().trim();
      final plain = plainBuffer.toString().trim();

      if (syncedLrc.isNotEmpty) {
        printINFO("Synced Lyrics generated from YouTube Captions for $videoId (First vocal at ${firstCaptionOffset?.inMilliseconds}ms)");
        return {
          "synced": syncedLrc,
          "plainLyrics": plain,
          "provider": "youtube_captions",
          "firstVocalMs": firstCaptionOffset?.inMilliseconds ?? 0,
        };
      }
    } catch (_) {
    } finally {
      yt.close();
    }
    return null;
  }

  /// Automatically adjusts studio lyrics (.lrc) timestamps by matching the first studio line with YouTube's true vocal onset
  static String alignStudioLyricsWithCaptions(String studioLrc, int ytFirstVocalMs) {
    if (studioLrc.trim().isEmpty || ytFirstVocalMs <= 0) return studioLrc;

    final regex = RegExp(r'\[(\d{2}):(\d{2})\.(\d{2,3})\](.*)');
    final lines = studioLrc.split('\n');
    int? studioFirstMs;

    for (final line in lines) {
      final match = regex.firstMatch(line.trim());
      if (match != null && match.group(4)!.trim().isNotEmpty) {
        final min = int.parse(match.group(1)!);
        final sec = int.parse(match.group(2)!);
        final msStr = match.group(3)!;
        final ms = int.parse(msStr.padRight(3, '0').substring(0, 3));
        studioFirstMs = (min * 60 + sec) * 1000 + ms;
        break;
      }
    }

    if (studioFirstMs == null) return studioLrc;

    // Delta between video's true vocal onset and studio track's start
    final deltaMs = ytFirstVocalMs - studioFirstMs;
    // Only adjust if there is an audible difference (> 400ms) and within reasonable intro bounds (< 90 seconds)
    if (deltaMs.abs() < 400 || deltaMs.abs() > 90000) return studioLrc;

    final buffer = StringBuffer();
    for (final line in lines) {
      final match = regex.firstMatch(line.trim());
      if (match != null) {
        final min = int.parse(match.group(1)!);
        final sec = int.parse(match.group(2)!);
        final msStr = match.group(3)!;
        final ms = int.parse(msStr.padRight(3, '0').substring(0, 3));
        int originalMs = (min * 60 + sec) * 1000 + ms;
        int alignedMs = originalMs + deltaMs;
        if (alignedMs < 0) alignedMs = 0;

        final alignedDuration = Duration(milliseconds: alignedMs);
        final mStr = alignedDuration.inMinutes.remainder(60).toString().padLeft(2, '0');
        final sStr = alignedDuration.inSeconds.remainder(60).toString().padLeft(2, '0');
        final milliStr = (alignedDuration.inMilliseconds.remainder(1000) ~/ 10).toString().padLeft(2, '0');
        String lineContent = match.group(4) ?? '';
        if (lineContent.contains('<') && lineContent.contains('>')) {
          final wordRegex = RegExp(r'<(\d{2}):(\d{2})\.(\d{2,3})>');
          lineContent = lineContent.replaceAllMapped(wordRegex, (wMatch) {
            final wMin = int.parse(wMatch.group(1)!);
            final wSec = int.parse(wMatch.group(2)!);
            final wMsStr = wMatch.group(3)!;
            final wMs = int.parse(wMsStr.padRight(3, '0').substring(0, 3));
            int wOriginalMs = (wMin * 60 + wSec) * 1000 + wMs;
            int wAlignedMs = wOriginalMs + deltaMs;
            if (wAlignedMs < 0) wAlignedMs = 0;
            final wDur = Duration(milliseconds: wAlignedMs);
            final wm = wDur.inMinutes.remainder(60).toString().padLeft(2, '0');
            final ws = wDur.inSeconds.remainder(60).toString().padLeft(2, '0');
            final wmillis = (wDur.inMilliseconds.remainder(1000) ~/ 10).toString().padLeft(2, '0');
            return '<$wm:$ws.$wmillis>';
          });
        }
        buffer.writeln('[$mStr:$sStr.$milliStr]$lineContent');
      } else {
        buffer.writeln(line);
      }
    }

    printINFO("Auto-aligned studio lyrics with YouTube video subtitles by ${deltaMs >= 0 ? '+' : ''}${deltaMs}ms");
    return buffer.toString().trim();
  }

  static Future<Map<String, dynamic>?> _fetchFromNetease(
      String cleanTitle, String cleanArtist) async {
    try {
      final query = '$cleanTitle $cleanArtist'.trim();
      final searchUrl =
          'https://music.163.com/api/search/get/web?csrf_token=type=1&offset=0&total=true&limit=3&s=${Uri.encodeComponent(query)}';
      final response = (await _dio.get(searchUrl)).data;
      if (response != null && response is Map && response['result'] != null) {
        final songs = response['result']['songs'];
        if (songs is List && songs.isNotEmpty) {
          final songId = songs[0]['id'];
          if (songId != null) {
            final lyricUrl =
                'https://music.163.com/api/song/lyric?os=pc&id=$songId&lv=-1&kv=-1&tv=-1';
