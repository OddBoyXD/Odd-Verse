        final sections = res['response']['sections'] as List;
        for (final sec in sections) {
          if (sec is Map && sec['type'] == 'song' && sec['hits'] is List) {
            final hits = sec['hits'] as List;
            if (hits.isNotEmpty) {
              final songPath = hits[0]?['result']?['path']?.toString();
