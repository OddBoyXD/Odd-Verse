              if (diff < minDiff && diff < 30) {
                minDiff = diff;
                bestSong = item;
              }
            }
          }
          bestSong ??= infoList.first as Map;
          hash = bestSong['hash']?.toString();
        }
      }

      final lyricSearchUrl = hash != null && hash.isNotEmpty
          ? 'https://lyrics.kugou.com/search?ver=1&man=yes&client=pc&hash=$hash'
          : 'https://lyrics.kugou.com/search?ver=1&man=yes&client=pc&keyword=${Uri.encodeComponent(query)}';
      final lyricRes = (await _dio.get(lyricSearchUrl)).data;
      if (lyricRes != null &&
          lyricRes is Map &&
          lyricRes['candidates'] is List) {
        final candidates = lyricRes['candidates'] as List;
        if (candidates.isNotEmpty) {
          final first = candidates.first as Map;
          final id = first['id']?.toString();
          final accesskey = first['accesskey']?.toString();
          if (id != null && accesskey != null) {
            final downloadUrl =
                'https://lyrics.kugou.com/download?ver=1&client=pc&id=$id&accesskey=$accesskey&fmt=lrc&charset=utf8';
            final downRes = (await _dio.get(downloadUrl)).data;
            if (downRes != null &&
                downRes is Map &&
                downRes['content'] != null) {
              final b64 = downRes['content'].toString();
              final decoded = utf8.decode(base64.decode(b64));
              if (decoded.trim().isNotEmpty) {
                final plain =
                    decoded.replaceAll(RegExp(r'\[.*?\]|<.*?>'), '').trim();
                printINFO("Synced Lyrics found via KuGou for $cleanTitle");
                return {
                  "synced": decoded.trim(),
                  "plainLyrics": plain,
                  "provider": "kugou",
                  "wordSynced":
                      decoded.contains('<') && decoded.contains('>'),
                };
              }
            }
          }
        }
      }
    } catch (_) {}
    return null;
  }

  static Future<Map<String, dynamic>?> _fetchFromLrclib(
      String cleanTitle, String cleanArtist, int durationSec) async {
    // 1. Exact lookup
    if (cleanArtist.isNotEmpty && cleanTitle.isNotEmpty) {
      try {
        final url =
            'https://lrclib.net/api/get?artist_name=${Uri.encodeComponent(cleanArtist)}&track_name=${Uri.encodeComponent(cleanTitle)}&duration=$durationSec';
        final response = (await _dio.get(url)).data;
        if (response != null && response is Map) {
          if (_isStrictMatch(response, cleanTitle, cleanArtist, durationSec)) {
            final synced = response["syncedLyrics"]?.toString();
            final plain = response["plainLyrics"]?.toString() ?? "";
            if (synced != null && synced.trim().isNotEmpty) {
              return {
                "synced": synced,
                "plainLyrics": plain,
                "provider": "lrclib",
                "wordSynced": false,
              };
            }
          }
        }
      } catch (_) {}
    }

    // 2. Search fallback
    if (cleanTitle.isNotEmpty) {
      try {
        final searchUrl = cleanArtist.isNotEmpty
            ? 'https://lrclib.net/api/search?track_name=${Uri.encodeComponent(cleanTitle)}&artist_name=${Uri.encodeComponent(cleanArtist)}'
            : 'https://lrclib.net/api/search?track_name=${Uri.encodeComponent(cleanTitle)}';
        final response = (await _dio.get(searchUrl)).data;
        if (response != null && response is List && response.isNotEmpty) {
          Map? bestMatch;
          int minDurDiff = 999999;
          for (final item in response) {
            if (item is Map &&
                _isStrictMatch(item, cleanTitle, cleanArtist, durationSec)) {
              final synced = item["syncedLyrics"]?.toString();
              if (synced != null && synced.trim().isNotEmpty) {
                final itemDur = (item["duration"] is num)
                    ? (item["duration"] as num).toInt()
                    : 0;
                final diff = (itemDur - durationSec).abs();
                if (diff < minDurDiff) {
                  minDurDiff = diff;
                  bestMatch = item;
                }
              }
            }
          }
          if (bestMatch != null) {
            return {
              "synced": bestMatch["syncedLyrics"].toString(),
              "plainLyrics": bestMatch["plainLyrics"]?.toString() ?? "",
              "provider": "lrclib",
              "wordSynced": false,
            };
          }
        }
      } catch (_) {}
    }
    return null;
  }

  static Future<Map<String, dynamic>?> _dispatchProvider(
      String providerId,
      String cleanTitle,
      String cleanArtist,
      int dur,
      String videoId,
      {Future<Map<String, dynamic>?>? ytCaptionsFuture}) {
    switch (providerId) {
      case 'lrc_red':
        return _fetchFromLrcRed(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'bini_lyrics':
        return _fetchFromBiniLyrics(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'better_lyrics':
        return _fetchFromBetterLyrics(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'better_lyrics_portato':
        return _fetchFromBetterLyricsPortato(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'paxsenix':
        return _fetchFromPaxSenix(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'paxsenix_spotify':
        return _fetchFromPaxSenixSpotify(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'paxsenix_musixmatch':
        return _fetchFromPaxSenixMusixmatch(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'lyrics_plus':
        return _fetchFromLyricsPlus(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'unison':
        return _fetchFromUnison(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'youtube_captions':
        return (ytCaptionsFuture ?? _fetchFromYouTubeCaptions(videoId))
            .catchError((_) => null);
      case 'ytmusic':
        return _fetchFromYouTubeMusic(videoId).catchError((_) => null);
      case 'kugou':
        return _fetchFromKuGou(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'lrclib':
        return _fetchFromLrclib(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'musixmatch':
        return _fetchFromMusixmatch(cleanTitle, cleanArtist, dur)
            .catchError((_) => null);
      case 'genius':
        return _fetchFromGenius(cleanTitle, cleanArtist)
            .catchError((_) => null);
      default:
        return Future.value(null);
    }
  }

  /// Search a specific provider or across all providers for manual lyrics search
  static Future<List<Map<String, dynamic>>> searchProvider(
      String providerId, String title, String artist,
      {int durationSec = 0, String videoId = ""}) async {
    final cleanTitle = cleanTrackTitle(title, artist: artist);
    final cleanArtist = cleanArtistName(artist);
    final results = <Map<String, dynamic>>[];

    if (providerId == 'all') {
      return searchAllProviders(title, artist, durationSec: durationSec);
    }

    final allSources = LyricsSourceInfo.loadSavedSources();
    final source = allSources.firstWhere(
      (s) => s.id == providerId,
      orElse: () => LyricsSourceInfo(
        id: providerId,
        label: providerId,
        detail: providerId,
        wordSynced: false,
      ),
    );

    final res = await _dispatchProvider(
        providerId, cleanTitle, cleanArtist, durationSec, videoId);
    if (res != null &&
        ((res['synced'] != null &&
                res['synced'].toString().trim().isNotEmpty) ||
            (res['plainLyrics'] != null &&
                res['plainLyrics'].toString().trim().isNotEmpty))) {
      results.add({
        ...res,
        'title': cleanTitle,
        'artist': cleanArtist,
        'sourceName':
            '${source.label}${res['wordSynced'] == true ? " (Word-synced 🍎)" : ""}',
      });
    }

    return results;
  }

  /// Search across all providers simultaneously for manual lyrics search
  static Future<List<Map<String, dynamic>>> searchAllProviders(
      String title, String artist,
      {int durationSec = 0}) async {
    final cleanTitle = cleanTrackTitle(title, artist: artist);
    final cleanArtist = cleanArtistName(artist);
    final results = <Map<String, dynamic>>[];
    final enabledSources =
        LyricsSourceInfo.loadSavedSources().where((s) => s.enabled).toList();

    final futures = enabledSources.map((src) async {
      final res = await _dispatchProvider(
          src.id, cleanTitle, cleanArtist, durationSec, "");
      if (res != null &&
          ((res['synced'] != null &&
                  res['synced'].toString().trim().isNotEmpty) ||
              (res['plainLyrics'] != null &&
                  res['plainLyrics'].toString().trim().isNotEmpty))) {
        results.add({
          ...res,
          'title': cleanTitle,
          'artist': cleanArtist,
          'sourceName':
              '${src.label}${res['wordSynced'] == true ? " (Word-synced 🍎)" : ""}',
        });
      }
    }).toList();

    await Future.wait(futures);
    return results;
  }

  static String _normalize(String input) {
    return input
        .toLowerCase()
        .replaceAll(RegExp(r'[^\w\s]'), '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
  }

  static String cleanTrackTitle(String title, {String? artist}) {
    String clean = title;

    // 1. Split by pipe '|', ' / ', ' // ' and take first part (common in YouTube music video titles)
    if (clean.contains('|')) {
      clean = clean.split('|')[0];
    }
    if (clean.contains(' / ')) {
      clean = clean.split(' / ')[0];
    }
    if (clean.contains(' // ')) {
      clean = clean.split(' // ')[0];
    }

    // 2. Handle "Artist - Title" vs "Title - Subtitle"
    final cleanArtist = cleanArtistName(artist);
    if (clean.contains(' - ') || clean.contains(' – ')) {
      final sep = clean.contains(' – ') ? ' – ' : ' - ';
      final parts = clean.split(sep);
      if (parts.length >= 2) {
        final p0 = _normalize(parts[0]);
        final p1 = _normalize(parts[1]);
        final a = _normalize(cleanArtist);
        if (a.isNotEmpty && (p0 == a || p0.contains(a) || a.contains(p0))) {
          // "Artist - Title" -> Take title (parts[1..])
          clean = parts.sublist(1).join(sep);
        } else if (a.isNotEmpty &&
            (p1 == a || p1.contains(a) || a.contains(p1))) {
          // "Title - Artist" -> Take title (parts[0])
          clean = parts[0];
        } else if (cleanArtist.isEmpty) {
          // If no artist given, parts[0] is often artist, parts[1] is title
          clean = parts.sublist(1).join(sep);
        }
      }
    }

    // 3. Remove (From "Movie Name") or [From 'Movie Name']
    clean = clean.replaceAll(
      RegExp(
        r'\s*[\(\[\{]\s*from\s+["\x27]?[^\)\]\}]+["\x27]?\s*[\)\]\}]',
        caseSensitive: false,
      ),
      '',
    );

    // 4. Remove metadata tags inside brackets/parentheses
    clean = clean.replaceAll(
      RegExp(
        r'\s*[\(\[\{][^\)\]\}]*(?:official|video|audio|lyrics|lyric|visualizer|remaster|hd|4k|extended|clean|explicit|live|mv|feat|ft\.|ost|soundtrack|full song|full audio|telemovie|promo|coke studio|teaser|trailer|slowed|reverb|sped up)[^\)\]\}]*[\)\]\}]',
        caseSensitive: false,
      ),
      '',
    );

    // 5. Remove (feat. ...), (ft. ...), [feat. ...]
    clean = clean.replaceAll(
      RegExp(
        r'\s*[\(\[\{]\s*(?:feat\.|ft\.|featuring)\s+[^\)\]\}]+[\)\]\}]',
        caseSensitive: false,
      ),
      '',
    );

    // 6. Remove (Prod. by ...), (Produced by ...)
    clean = clean.replaceAll(
      RegExp(
        r'\s*[\(\[\{]\s*(?:prod\.|produced\s+by)\s+[^\)\]\}]+[\)\]\}]',
        caseSensitive: false,
      ),
      '',
    );

    // 7. Remove version tags like (Bonus Track), (Deluxe Edition), (Acoustic Version)
    clean = clean.replaceAll(
      RegExp(
        r'\s*[\(\[\{]\s*(?:bonus\s*track|deluxe(?:\s*edition)?|anniversary(?:\s*edition)?|acoustic(?:\s*version)?|radio\s*edit)\s*[\)\]\}]',
        caseSensitive: false,
      ),
      '',
    );

    // 8. Remove trailing - Official Video / Music Video / Lyric Video / Remastered / etc. without parentheses
    clean = clean.replaceAll(
      RegExp(
        r'\s*-\s*(?:official\s*(?:video|audio|music\s*video|lyric\s*video)?|music\s*video|lyric\s*video|visualizer|hd|4k|remastered|lyrics?).*$',
        caseSensitive: false,
      ),
      '',
    );

    // 9. Remove trailing metadata keywords at the end of title
    clean = clean.replaceAll(
      RegExp(
        r'\s+(?:official\s*(?:video|audio|music\s*video|lyric\s*video)|music\s*video|lyric\s*video|visualizer)\s*$',
        caseSensitive: false,
      ),
      '',
    );

    // 10. Remove trailing feat. / ft.
    clean = clean.replaceAll(
      RegExp(r'\s*(?:feat\.|ft\.|featuring)\s+.*$', caseSensitive: false),
      '',
    );

    // 11. Remove hashtags and promotional markers
    clean = clean.replaceAll(RegExp(r'#\w+'), '');

    // 12. Remove trailing dashes/punctuation
    clean = clean.replaceAll(RegExp(r'[\s\-_|:]+$'), '').trim();
    return clean.isEmpty ? title.trim() : clean;
  }

  static String cleanArtistName(String? artist) {
    if (artist == null || artist.trim().isEmpty) return '';
    String clean = artist.trim();
    // Remove " - Topic" from auto-generated channels
    clean =
        clean.replaceAll(RegExp(r'\s*-\s*Topic$', caseSensitive: false), '');
    clean = clean.replaceAll(RegExp(r'\s*VEVO$', caseSensitive: false), '');
    clean = clean.replaceAll(RegExp(r'\s*Official$', caseSensitive: false), '');
    clean = clean.replaceAll(RegExp(r'\s*Channel$', caseSensitive: false), '');
    // Take primary artist before comma, &, x, X, feat, ft
    clean = clean.split(',')[0].split('&')[0].split(
      RegExp(r'\s+[xX]\s+'),
    )[0].split(
      RegExp(r'\s+(?:feat\.|ft\.|featuring)\s+', caseSensitive: false),
    )[0].trim();
    return clean;
  }

  /// Verifies that candidate from LRCLIB genuinely matches the target track
  static bool _isStrictMatch(
    Map item,
    String cleanTitle,
    String cleanArtist,
    int expectedDurationSec,
  ) {
    final candidateTrack = _normalize(
      (item["trackName"] ?? item["name"] ?? "").toString(),
    );
    final targetTrack = _normalize(cleanTitle);

    if (candidateTrack.isEmpty || targetTrack.isEmpty) return false;

    // Direct equality or substring containment
    bool titleMatches = (candidateTrack == targetTrack) ||
        candidateTrack.startsWith(targetTrack) ||
        targetTrack.startsWith(candidateTrack) ||
        candidateTrack.contains(targetTrack) ||
        targetTrack.contains(candidateTrack);

    if (!titleMatches) {
      // Word overlap check: at least 60% of target track words must be present
      final cWords =
          candidateTrack.split(' ').where((w) => w.length > 1).toSet();
      final tWords =
          targetTrack.split(' ').where((w) => w.length > 1).toSet();
      if (tWords.isNotEmpty && cWords.isNotEmpty) {
        final common = tWords.intersection(cWords);
        if (common.length / tWords.length >= 0.6) {
          titleMatches = true;
        }
      }
    }

    if (!titleMatches) return false;

    // Check duration tolerance
    final candidateArtist = _normalize((item["artistName"] ?? "").toString());
    final targetArtist = _normalize(cleanArtist);
    bool artistMatches = false;
    if (targetArtist.isNotEmpty && candidateArtist.isNotEmpty) {
      artistMatches = candidateArtist == targetArtist ||
          candidateArtist.contains(targetArtist) ||
          targetArtist.contains(candidateArtist);
    }

    final itemDur = (item["duration"] is num)
        ? (item["duration"] as num).toInt()
        : 0;
    if (expectedDurationSec > 0 && itemDur > 0) {
      final diff = (itemDur - expectedDurationSec).abs();
      if (artistMatches) {
        return diff <= 50; // generous tolerance when artist is confirmed
      } else {
        return diff <= 25; // stricter tolerance when artist is not confirmed
      }
    }

    return true;
  }

  static Future<Map<String, dynamic>?> getSyncedLyrics(
      MediaItem song, int durInSec) async {
    final lyricsBox = await _getLyricsBox();

    // 1. Check local cache
    if (lyricsBox.containsKey(song.id)) {
      try {
        final cached = lyricsBox.get(song.id);
        if (cached is Map) {
          return Map<String, dynamic>.from(cached);
        }
      } catch (_) {}
    }

    final cleanTitle = cleanTrackTitle(song.title, artist: song.artist);
    final cleanArtist = cleanArtistName(song.artist);
    final dur = song.duration?.inSeconds ?? durInSec;
    String? fallbackPlain;

    final enabledSources =
        LyricsSourceInfo.loadSavedSources().where((s) => s.enabled).toList();

    final Map<String, Map<String, dynamic>> providerResults = {};

    // Tier 1: Fast parallel check of the primary word-synced sources first (lrc_red, better_lyrics, kugou, lrclib)
    final tier1Ids = {'lrc_red', 'better_lyrics', 'kugou', 'lrclib'};
    final tier1Sources =
        enabledSources.where((s) => tier1Ids.contains(s.id)).toList();

    await Future.wait(tier1Sources.map((source) async {
      try {
        final res = await _dispatchProvider(
          source.id,
          cleanTitle,
          cleanArtist,
          dur,
          song.id,
        );
        if (res != null) {
          providerResults[source.id] = res;
        }
      } catch (_) {}
    }));

    // Check if any Tier 1 source gave us word-synced lyrics
    Map<String, dynamic>? bestLyrics;
    for (final src in tier1Sources) {
      final cand = providerResults[src.id];
      if (cand != null &&
          cand['wordSynced'] == true &&
          cand['synced'] != null &&
          cand['synced'].toString().trim().isNotEmpty) {
        bestLyrics = Map<String, dynamic>.from(cand);
        break;
      }
    }

    // Tier 2: If no word-synced lyrics from Tier 1, query remaining enabled sources in parallel
    if (bestLyrics == null) {
      final tier2Sources =
          enabledSources.where((s) => !tier1Ids.contains(s.id)).toList();
      if (tier2Sources.isNotEmpty) {
        await Future.wait(tier2Sources.map((source) async {
          try {
            final res = await _dispatchProvider(
              source.id,
              cleanTitle,
              cleanArtist,
              dur,
              song.id,
            );
            if (res != null) {
              providerResults[source.id] = res;
            }
          } catch (_) {}
        }));
      }

      // Check all sources for word-synced lyrics
      for (final src in enabledSources) {
        final cand = providerResults[src.id];
        if (cand != null &&
            cand['wordSynced'] == true &&
            cand['synced'] != null &&
            cand['synced'].toString().trim().isNotEmpty) {
          bestLyrics = Map<String, dynamic>.from(cand);
          break;
        }
      }

      // Priority 2: Line-synced lyrics in user provider preference order
      if (bestLyrics == null) {
        for (final src in enabledSources) {
          final cand = providerResults[src.id];
          if (cand != null &&
              cand['synced'] != null &&
              cand['synced'].toString().trim().isNotEmpty) {
            bestLyrics = Map<String, dynamic>.from(cand);
            break;
          }
        }
      }

      // Priority 3: Only check YouTube captions if no lyrics were found anywhere
      if (bestLyrics == null) {
        try {
          final ytCaptions = await _fetchFromYouTubeCaptions(song.id);
          if (ytCaptions != null &&
              ytCaptions['synced'] != null &&
              ytCaptions['synced'].toString().trim().isNotEmpty) {
            bestLyrics = Map<String, dynamic>.from(ytCaptions);
          }
        } catch (_) {}
      }
    }

    // Gather plain lyrics fallback from candidates if any
    for (final src in enabledSources) {
      final cand = providerResults[src.id];
      if (cand != null &&
          cand['plainLyrics'] != null &&
          cand['plainLyrics'].toString().trim().isNotEmpty) {
        fallbackPlain ??= cand['plainLyrics'].toString().trim();
        break;
      }
    }

    if (bestLyrics != null) {
      String synced = bestLyrics['synced']?.toString() ?? '';
      final int ytFirstVocalMs = (bestLyrics['firstVocalMs'] is int)
          ? (bestLyrics['firstVocalMs'] as int)
          : 0;
      if (synced.isNotEmpty &&
          ytFirstVocalMs > 0 &&
          bestLyrics['provider'] != 'youtube_captions') {
        synced = alignStudioLyricsWithCaptions(synced, ytFirstVocalMs);
        bestLyrics['synced'] = synced;
        bestLyrics['captionAligned'] = true;
      }
      await lyricsBox.put(song.id, bestLyrics);
      return bestLyrics;
    }

    // 6. Tier 6: YouTube Music Official Lyrics Fallback (Plain Text)
    try {
      if (Get.isRegistered<MusicServices>()) {
        final musicServices = Get.find<MusicServices>();
        final related = await musicServices.getWatchPlaylist(
          videoId: song.id,
          onlyRelated: true,
        );
        final lyricsId = related['lyrics'];
        if (lyricsId != null) {
          final ytLyrics = await musicServices.getLyrics(lyricsId);
          if (ytLyrics != null && ytLyrics.toString().trim().isNotEmpty) {
            printINFO("Official YouTube Music Lyrics retrieved for ${song.title}");
            final lyricsData = {
              "synced": "",
              "plainLyrics": ytLyrics.toString().trim(),
              "provider": "ytmusic",
            };
            await lyricsBox.put(song.id, lyricsData);
            return lyricsData;
          }
        }
      }
    } catch (e) {
      printERROR("YTMusic Lyrics fetch error: $e");
    }

    // 7. Tier 7: Return fallback plain lyrics if available
    if (fallbackPlain != null && fallbackPlain.trim().isNotEmpty) {
      final lyricsData = {
        "synced": "",
        "plainLyrics": fallbackPlain,
      };
      await lyricsBox.put(song.id, lyricsData);
      return lyricsData;
    }

    return null;
  }
